"""Human-readable Markdown reporting."""

from collections import defaultdict
from pathlib import Path

from infraguard.models import Finding, ScanReport, Severity


def _escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def render_markdown(report: ScanReport, minimum: Severity | None = None) -> str:
    """Render a deterministic Markdown report."""
    findings = [
        finding
        for finding in report.findings
        if minimum is None or finding.severity.rank >= minimum.rank
    ]
    status = "PASSED" if report.summary.passed else "FAILED"
    lines = [
        "# InfraGuard Scan Report",
        "",
        f"**{status}** · Scan `{report.scan_id}` · {report.finished_at.isoformat()}",
        "",
        f"Targets: {', '.join(f'`{target}`' for target in report.targets)}",
        "",
        "## Summary",
        "",
        "| Resources | Findings | Critical | High | Medium | Low |",
        "|---:|---:|---:|---:|---:|---:|",
        "| "
        f"{report.summary.resources_scanned} | {report.summary.findings_total} | "
        f"{report.summary.by_severity.CRITICAL} | {report.summary.by_severity.HIGH} | "
        f"{report.summary.by_severity.MEDIUM} | {report.summary.by_severity.LOW} |",
    ]
    grouped: dict[Severity, list[Finding]] = defaultdict(list)
    for finding in findings:
        grouped[finding.severity].append(finding)
    for severity in Severity:
        if not grouped[severity]:
            continue
        lines.extend(
            [
                "",
                f"## {severity.value}",
                "",
                "| Policy | Resource | Message | Remediation |",
                "|---|---|---|---|",
            ]
        )
        for finding in grouped[severity]:
            lines.append(
                f"| {finding.policy_id} | `{finding.resource.key()}` | "
                f"{_escape(finding.message)} | {_escape(finding.remediation)} |"
            )
    lines.extend(
        [
            "",
            "## Validator runs",
            "",
            "| Validator | Duration (ms) | Resources | Findings |",
            "|---|---:|---:|---:|",
        ]
    )
    for run in report.validators:
        lines.append(
            f"| {run.name} | {run.duration_ms:.2f} | {run.resources_checked} | {run.findings} |"
        )
    lines.extend(["", f"Generated by InfraGuard v{report.tool_version}.", ""])
    return "\n".join(lines)


def write_markdown(report: ScanReport, output: Path) -> None:
    """Write Markdown output, creating its parent directory."""
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_markdown(report))
